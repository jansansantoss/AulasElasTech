package org.example;

public class TresNotas {
    static void main(String[] args) {
        double nota1 = 8;
        double nota2 = 6;
        double nota3 = 10;

        double soma = nota1 + nota2 + nota3;
        double media = soma / 3;

        System.out.println("Soma das notas: " + soma);
        System.out.println("Média das notas: " + media);
    }

}
